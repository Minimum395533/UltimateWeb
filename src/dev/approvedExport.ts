import { validateAnimationFrames } from './frameDataModel.ts';
import type { AnimationDraft, ApprovedAnimation } from '../types/frameData.ts';

/**
 * Builds the approved record for one draft. Throws when the draft does not
 * match the locked frame count, so a mismatched animation never ships.
 */
export function createApprovedAnimation(
  draft: AnimationDraft,
  lockedFrameCount: number,
  approvedAt: string,
): ApprovedAnimation {
  if (draft.frames.length !== lockedFrameCount) {
    throw new Error(
      `${draft.animationId}: the draft has ${draft.frames.length} frames but the locked count is ${lockedFrameCount}. Fix it in the editor first.`,
    );
  }
  const error = validateAnimationFrames(draft.frames, lockedFrameCount);
  if (error) throw new Error(`${draft.animationId}: ${error}`);
  return {
    animationId: draft.animationId,
    name: draft.name,
    frameCount: lockedFrameCount,
    approvedAt,
    sourceDraftId: draft.id,
    sourceDraftUpdatedAt: draft.updatedAt,
    frames: draft.frames.map((frame) => ({ ...frame, referenceFrame: null })),
  };
}

/** Source text for src/data/falcon/approvedAnimations.ts, sorted by animation id. */
export function renderApprovedModule(records: Readonly<Record<string, ApprovedAnimation>>): string {
  const sorted = Object.fromEntries(
    Object.keys(records).sort().map((id) => [id, records[id]]),
  );
  const body = Object.keys(sorted).length ? JSON.stringify(sorted, null, 2) : '{}';
  return [
    '// Generated by `npm run approve-animations`. Do not edit by hand.',
    '// Only animations the user approved in chat are exported here.',
    "import type { ApprovedAnimation } from '../../types/frameData.ts';",
    '',
    `export const APPROVED_ANIMATIONS: Readonly<Record<string, ApprovedAnimation>> = ${body};`,
    '',
  ].join('\n');
}
